import '../models/custom_material_models.dart';

/// Well-known base materials. Composition values are the **maximum** limits
/// of the product standard (heat analysis, thinnest/typical thickness range
/// noted per group) -- not measured values -- so a CET computed from them is
/// a conservative upper bound. A `null` element means the standard does not
/// specify a limit for it; such materials are left out of the preheat
/// calculator's "load from library" list ([isCetReady]) rather than guessed.
/// Values were transcribed from the standards listed per group and should
/// be verified against the current edition before relying on them.
class CatalogBaseMaterial {
  const CatalogBaseMaterial(
    this.name,
    this.standard,
    this.group,
    this.description, {
    this.c,
    this.si,
    this.mn,
    this.cr,
    this.mo,
    this.ni,
    this.cu,
    this.v,
    this.cetApplicable = false,
  });

  /// Short primary label (e.g. `S355J2`, `1.4404 / 316L`).
  final String name;
  final String standard;
  final String group;
  final String description;
  final double? c;
  final double? si;
  final double? mn;
  final double? cr;
  final double? mo;
  final double? ni;
  final double? cu;
  final double? v;

  /// True for ferritic / low-alloy steels where EN 1011-2 CET is meaningful.
  final bool cetApplicable;

  static const idPrefix = 'catalog:';

  String get id => '$idPrefix${standard.toLowerCase()}:${name.toLowerCase()}'
      .replaceAll(RegExp(r'\s+'), '_');

  /// All six CET inputs are specified by the standard.
  bool get isCetReady =>
      cetApplicable &&
      c != null &&
      mn != null &&
      cr != null &&
      mo != null &&
      ni != null &&
      cu != null;

  CustomBaseMaterial toMaterial() => CustomBaseMaterial(
    id: id,
    name: name,
    designation: standard,
    notes: description,
    updatedAtEpochMs: 0,
    carbonPercent: c,
    siliconPercent: si,
    manganesePercent: mn,
    chromiumPercent: cr,
    molybdenumPercent: mo,
    nickelPercent: ni,
    copperPercent: cu,
    vanadiumPercent: v,
  );
}

