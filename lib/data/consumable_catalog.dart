/// Extra filler metals / electrodes beyond the built-in [ConsumablePreset]
/// list. Only real standard classifications (AWS A5.x / ISO) are listed;
/// no proprietary brand products.
///
/// The calculator models efficiency and deposition rate per *process*
/// ([WeldingDefaults]), so the only per-product number needed here is the
/// weld-metal density -- a typical value for the alloy family (carbon and
/// low-alloy steel 7.85, austenitic stainless 7.90-8.00, aluminium
/// 2.66-2.84, nickel alloys 8.2-8.9 g/cm3). They are typical handbook
/// values, not certified per-product data.
///
/// Catalog entries reach the calculator as [CustomFillerMaterial] snapshots
/// with a `catalog:` id and `updatedAtEpochMs: 0`, so saved calculations
/// stay readable by older builds and independent of later catalog edits.
class CatalogConsumable {
  const CatalogConsumable(
    this.label,
    this.specification,
    this.family,
    this.densityGPerCm3,
    this.processes,
    this.description,
  );

  /// Short classification shown as the primary label (e.g. `E7018-1`).
  final String label;

  /// Standard the classification comes from (e.g. `AWS A5.1`).
  final String specification;
  final ConsumableFamily family;
  final double densityGPerCm3;
  final List<WeldingProcess> processes;
  final String description;

  static const idPrefix = 'catalog:';

  String get id =>
      '$idPrefix${specification.toLowerCase()}:${label.toLowerCase()}'
          .replaceAll(RegExp(r'\s+'), '_');

  CustomFillerMaterial toFiller() => CustomFillerMaterial(
    id: id,
    name: label,
    family: family,
    awsSpecification: specification,
    densityGPerCm3: densityGPerCm3,
    notes: description,
    updatedAtEpochMs: 0,
  );
}

